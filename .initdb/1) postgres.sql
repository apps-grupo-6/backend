CREATE TABLE public.users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    password varchar(150) NOT NULL,
    created_at timestamp NOT NULL,
    last_login_at timestamp,
    password_updated_at timestamp
);

CREATE TABLE public.roles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(17) NOT NULL UNIQUE
);

CREATE TABLE public.role_permissions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id integer NOT NULL,
    endpoint varchar NOT NULL,
    method varchar NOT NULL,
    CONSTRAINT fk_role_permissions_role
        FOREIGN KEY (role_id) REFERENCES public.roles (id)
        ON DELETE CASCADE,
    CONSTRAINT uq_role_permissions UNIQUE (role_id, endpoint, method)
);

CREATE TABLE public.user_roles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    role_id integer DEFAULT 1 NOT NULL,
    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id) REFERENCES public.users (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (role_id) REFERENCES public.roles (id)
        ON DELETE CASCADE,
    CONSTRAINT uq_user_roles UNIQUE (user_id, role_id)
);

CREATE TABLE public.user_information (
    user_id integer NOT NULL UNIQUE,
    first_name varchar(50) NOT NULL,
    last_name varchar(50) NOT NULL,
    telephone varchar(14) NOT NULL,
    contact_email varchar(100) NOT NULL,
    updated_at timestamp,
    CONSTRAINT fk_user_information_user
        FOREIGN KEY (user_id) REFERENCES public.users (id)
        ON DELETE CASCADE
);

CREATE TABLE public.user_controls (
    user_id integer NOT NULL UNIQUE,
    email_verified boolean DEFAULT false NOT NULL,
    email_verified_at timestamp,
    is_banned boolean DEFAULT false NOT NULL,
    banned_at timestamp,
    force_disconnect boolean DEFAULT false NOT NULL,
    disconnected_at timestamp,
    is_suspicious boolean DEFAULT false NOT NULL,
    suspicious_at timestamp,
    ban_request_id varchar(20),
    disconnect_request_id varchar(20),
    suspicious_request_id varchar(20),
    CONSTRAINT fk_user_controls_user
        FOREIGN KEY (user_id) REFERENCES public.users (id)
        ON DELETE CASCADE
);

CREATE TABLE public.otp_tokens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    token varchar(6) NOT NULL,
    expires_at timestamp NOT NULL,
    type varchar(12) NOT NULL,
    CONSTRAINT fk_otp_tokens_user
        FOREIGN KEY (user_id) REFERENCES public.users (id)
        ON DELETE CASCADE,
    CONSTRAINT uq_otp_tokens_user_type UNIQUE (user_id, type)
);

CREATE TABLE public.requests (
    id varchar(20) PRIMARY KEY,
    user_id integer NOT NULL,
    method varchar(6) NOT NULL,
    endpoint varchar(100) NOT NULL,
    code varchar(4) NOT NULL,
    execution_time double precision NOT NULL,
    executed_at timestamp DEFAULT now() NOT NULL,
    CONSTRAINT fk_requests_user
        FOREIGN KEY (user_id) REFERENCES public.users (id)
        ON DELETE CASCADE
);

CREATE TABLE public.disciplines (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE,
    intensity varchar(5) NOT NULL
);

CREATE TABLE public.locations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id integer NOT NULL,
    country_code varchar(2) NOT NULL,
    city varchar(50) NOT NULL,
    address varchar(50) NOT NULL,
    created_at timestamp NOT NULL,
    updated_at timestamp,
    lat float NOT NULL,
    lng float NOT NULL,
    name varchar NOT NULL,
    CONSTRAINT fk_locations_owner
        FOREIGN KEY (owner_id) REFERENCES public.users (id)
        ON DELETE CASCADE,
    CONSTRAINT uq_locations UNIQUE (owner_id, name)
);

CREATE TABLE public.classes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id integer NOT NULL,
    location_id integer NOT NULL,
    discipline_id integer NOT NULL,
    scheduled_at timestamp NOT NULL,
    ended_at timestamp,
    max_participants integer NOT NULL,
    qr varchar(150) NOT NULL,
    status varchar(11) DEFAULT 'NOT STARTED' NOT NULL,
    created_at timestamp,
    updated_at timestamp,
    CONSTRAINT fk_classes_professor
        FOREIGN KEY (professor_id) REFERENCES public.users (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_classes_location
        FOREIGN KEY (location_id) REFERENCES public.locations (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_classes_discipline
        FOREIGN KEY (discipline_id) REFERENCES public.disciplines (id)
        ON DELETE CASCADE
);

CREATE TABLE public.class_participants (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id integer NOT NULL,
    user_id integer NOT NULL,
    confirmed_at timestamp,
    status varchar(13) DEFAULT 'NOT CONFIRMED' NOT NULL,
    added_at timestamp NOT NULL,
    updated_at timestamp,
    CONSTRAINT fk_class_participants_class
        FOREIGN KEY (class_id) REFERENCES public.classes (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_class_participants_user
        FOREIGN KEY (user_id) REFERENCES public.users (id)
        ON DELETE CASCADE,
    CONSTRAINT uq_class_participants UNIQUE (class_id, user_id)
